// Captions (SEL-06): track shaping, json3 URL rewrite, the auto-select order, the persistence
// rule and cue post-processing with a forward lookup cursor. Qt-free; the JSON walking of the
// InnerTube player answer, the yt-dlp info dict and the json3 body is in CaptionService.

#include <cstddef>
#include <cstdint>
#include "TextParse.h"
#include <string>
#include <vector>

namespace nordtile { namespace video { namespace catalog {

// One track as the source lists it, before shaping.
struct CaptionSource {
    std::string url;            // as supplied (any fmt, possibly protocol-relative)
    std::string languageCode;   // "en", "pt-BR", "en-orig" (yt-dlp), "live_chat"
    std::string name;           // display name as supplied
    bool autoGenerated;         // kind == "asr" / yt-dlp automatic_captions
    bool translatable;
    bool isTranslation;         // yt-dlp: an automatic_captions entry whose URL carries tlang
    CaptionSource() : autoGenerated(false), translatable(true), isTranslation(false) {}
};

struct CaptionLanguage {
    std::string code;
    std::string name;
};

struct CaptionTrack {
    std::string key;            // unique in its set: "en", "en#2", "asr:en", "tlang:fr"
    std::string code;           // the language code that persists ("en", "pt-BR", "fr")
    std::string name;
    std::string url;            // json3 URL ready to GET
    bool autoGenerated;
    bool translation;
    CaptionTrack() : autoGenerated(false), translation(false) {}
};

struct CaptionTrackSet {
    std::vector<CaptionTrack> real;          // manual tracks and one ASR per language, source order
    std::vector<CaptionTrack> translations;  // source order; none for a language in `real`
    bool empty() const { return real.empty() && translations.empty(); }
    const CaptionTrack *find(const std::string &key) const;
};

// The URL with any fmt parameter removed and fmt=json3 appended; "//" and "/" made absolute.
std::string json3Url(const std::string &url);
// The URL with any tlang replaced by `code`, as json3.
std::string translationUrl(const std::string &url, const std::string &code);
// baseLanguage() (lower-case primary subtag: "pt-BR" -> "pt", "en-orig" -> "en") is TextParse's.
bool sameCode(const std::string &a, const std::string &b);   // case-insensitive, '_' == '-'

// Shapes tracks. `translationLanguages` are offered from the ASR track (else the first
// translatable track) with tlang; yt-dlp translation entries (isTranslation) join the same
// list. live_chat is skipped, one ASR track is kept per language, a translation is dropped when
// a real track has its exact code, and a yt-dlp "-orig" suffix is folded into the base code.
CaptionTrackSet shapeCaptionTracks(const std::vector<CaptionSource> &sources,
                                   const std::vector<CaptionLanguage> &translationLanguages);

// The switch for auto-translated tracks (a real track asked for with tlang=<code>).
// kCaptionTranslationsOffered is the shipped value, and it is false: the provider answers
// HTTP 429 to an anonymous tlang request (checked live 2026-11-10), and a choice that draws no
// text is worse than no choice. While off, the lists the catalog hands out (CaptionService::
// tracksFromPlayer / tracksFromYtDlp, so the caption page, playback.captionTracks and the
// auto-select) hold no translation. shapeCaptionTracks itself still builds them, and the tests
// keep covering them, so setting the constant to true brings them back the day the request works.
extern const bool kCaptionTranslationsOffered;
bool captionTranslationsOffered();
void setCaptionTranslationsOffered(bool on);   // tests; starts as kCaptionTranslationsOffered
// `tracks` as offered to the user: unchanged while translations are offered, else without them.
CaptionTrackSet offeredCaptionTracks(const CaptionTrackSet &tracks);

// Persisted preference values: "" = never chosen (captions start off), "off" = explicit Off,
// else a language code.
extern const char *const kCaptionsOff;

enum class CaptionMatch { None, ExactReal, ExactTranslation, BaseReal, BaseTranslation };

struct CaptionAutoPick {
    CaptionMatch match;
    std::string key;            // empty when match == None
    CaptionAutoPick() : match(CaptionMatch::None) {}
};

// SEL-06 order: 1 exact code among real tracks, 2 exact among translations, 3 base language
// among real tracks, 4 base among translations. Manual tracks beat ASR at the same step, and a
// track whose code equals the base exactly beats a sibling variant at steps 3 and 4.
CaptionAutoPick autoSelectCaption(const CaptionTrackSet &tracks, const std::string &preferred);

// Holds the persisted preference and the current choice of one video. Only explicit picks
// change the preference ("Off" included); auto-select never writes it back.
class CaptionSelection {
public:
    explicit CaptionSelection(const std::string &preferred = std::string()) : preferred_(preferred) {}
    const std::string &preferred() const { return preferred_; }
    const std::string &currentKey() const { return current_; }
    CaptionMatch lastMatch() const { return match_; }

    // New video: picks by the preference without touching it. Returns the chosen key.
    std::string apply(const CaptionTrackSet &tracks);
    // Explicit pick. Returns true when the preference changed (the caller persists it).
    bool pick(const CaptionTrackSet &tracks, const std::string &key);
    bool pickOff();

private:
    std::string preferred_;
    std::string current_;
    CaptionMatch match_ = CaptionMatch::None;
};

// ---- cues ----

struct CaptionEvent {
    std::int64_t startMs;
    std::int64_t durationMs;    // < 0 when the event has no duration
    std::string text;           // joined segments, raw
    CaptionEvent() : startMs(0), durationMs(-1) {}
    CaptionEvent(std::int64_t s, std::int64_t d, const std::string &t) : startMs(s), durationMs(d), text(t) {}
};

struct CaptionCue {
    std::int64_t startMs;
    std::int64_t endMs;
    std::string text;
    CaptionCue() : startMs(0), endMs(0) {}
    CaptionCue(std::int64_t s, std::int64_t e, const std::string &t) : startMs(s), endMs(e), text(t) {}
};

const std::int64_t kCueDefaultDurationMs = 4000;
const std::int64_t kCueRepeatMergeMs = 50;
const std::int64_t kCueMinimumMs = 50;

// Collapses runs of whitespace (including newlines) into single spaces and trims.
std::string collapseWhitespace(const std::string &text);

// Post-processing: collapse text and drop empties; no duration -> 4 s; sort by start; merge a
// line repeated within 50 ms of the previous cue's end (rolling ASR); end each cue no later
// than the next one's start; drop cues shorter than 50 ms. The result is sorted and has no
// overlaps.
std::vector<CaptionCue> buildCues(const std::vector<CaptionEvent> &events);

// Index of the cue showing at `ms` in sorted, non-overlapping cues, or -1 (binary search).
int cueIndexAt(const std::vector<CaptionCue> &cues, std::int64_t ms);

// Forward cursor for position ticks: advances from the last cue and rescans on a backward jump.
class CueCursor {
public:
    void reset() { index_ = 0; rescans_ = 0; }
    // Returns the index of the cue at `ms`, or -1.
    int at(const std::vector<CaptionCue> &cues, std::int64_t ms);
    int rescans() const { return rescans_; }
private:
    std::size_t index_ = 0;
    int rescans_ = 0;
};

}}}
