const CaptionTrack *CaptionTrackSet::find(const std::string &key) const {
    for (const CaptionTrack &t : real) if (t.key == key) return &t;
    for (const CaptionTrack &t : translations) if (t.key == key) return &t;
    return nullptr;
}

std::string json3Url(const std::string &url) {
    return appendParam(withoutParam(absolute(url), "fmt"), "fmt=json3");
}

std::string translationUrl(const std::string &url, const std::string &code) {
    const std::string stripped = withoutParam(withoutParam(absolute(url), "fmt"), "tlang");
    return appendParam(appendParam(stripped, "tlang=" + code), "fmt=json3");
}

bool sameCode(const std::string &a, const std::string &b) { return !a.empty() && lower(a) == lower(b); }

CaptionTrackSet shapeCaptionTracks(const std::vector<CaptionSource> &sources,
                                   const std::vector<CaptionLanguage> &translationLanguages) {
    CaptionTrackSet set;
    std::map<std::string, int> manualPerCode;
    std::set<std::string> asrCodes;
    const CaptionSource *translationBase = nullptr;
    std::vector<CaptionLanguage> offered;

    for (const CaptionSource &s : sources) {
        if (s.url.empty() || s.languageCode.empty() || isLiveChat(s.languageCode)) continue;
        if (s.isTranslation) {
            CaptionLanguage l;
            l.code = s.languageCode;
            l.name = s.name;
            offered.push_back(l);
            continue;
        }
        CaptionTrack t;
        t.code = s.autoGenerated ? foldOrig(s.languageCode) : s.languageCode;
        t.name = s.name.empty() ? t.code : s.name;
        t.url = json3Url(s.url);
        t.autoGenerated = s.autoGenerated;
        if (s.autoGenerated) {
            if (!asrCodes.insert(lower(t.code)).second) continue;   // one ASR track per language
            t.key = "asr:" + t.code;
            if (s.translatable && (!translationBase || !translationBase->autoGenerated)) translationBase = &s;
        } else {
            const int n = ++manualPerCode[lower(t.code)];
            t.key = n == 1 ? t.code : t.code + "#" + std::to_string(n);
            if (s.translatable && !translationBase) translationBase = &s;
        }
        set.real.push_back(t);
    }

    if (translationBase) offered.insert(offered.begin(), translationLanguages.begin(), translationLanguages.end());

    std::set<std::string> taken;
    for (const CaptionTrack &t : set.real) taken.insert(lower(t.code));
    for (std::size_t i = 0; i < offered.size(); ++i) {
        const CaptionLanguage &l = offered[i];
        if (l.code.empty() || isLiveChat(l.code)) continue;
        if (!taken.insert(lower(l.code)).second) continue;   // a real track (or an earlier entry) has it
        CaptionTrack t;
        t.code = l.code;
        t.name = l.name.empty() ? l.code : l.name;
        t.translation = true;
        t.key = "tlang:" + l.code;
        // Entries from translationLanguages come first in `offered`; yt-dlp entries carry their own URL.
        const bool fromList = translationBase && i < translationLanguages.size();
        if (fromList) {
            t.url = translationUrl(translationBase->url, l.code);
        } else {
            for (const CaptionSource &s : sources)
                if (s.isTranslation && s.languageCode == l.code) { t.url = json3Url(s.url); break; }
        }
        if (t.url.empty()) continue;
        set.translations.push_back(t);
    }
    return set;
}

const bool kCaptionTranslationsOffered = false;

