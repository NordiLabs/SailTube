std::string lower(const std::string &s) {
    std::string out(s);
    for (char &c : out) {
        if (c >= 'A' && c <= 'Z') c = static_cast<char>(c - 'A' + 'a');
        else if (c == '_') c = '-';
    }
    return out;
}

bool isSpace(char c) { return c == ' ' || c == '\t' || c == '\n' || c == '\r' || c == '\v' || c == '\f'; }

// Removes every query parameter named `name` (the fragment, if any, is kept).
std::string withoutParam(const std::string &url, const std::string &name) {
    std::string fragment;
    std::string head = url;
    const std::size_t hash = head.find('#');
    if (hash != std::string::npos) { fragment = head.substr(hash); head = head.substr(0, hash); }
    const std::size_t q = head.find('?');
    if (q == std::string::npos) return head + fragment;
    const std::string base = head.substr(0, q);
    const std::string query = head.substr(q + 1);
    std::string kept;
    std::size_t pos = 0;
    while (pos <= query.size()) {
        std::size_t amp = query.find('&', pos);
        if (amp == std::string::npos) amp = query.size();
        const std::string part = query.substr(pos, amp - pos);
        const std::string key = part.substr(0, part.find('='));
        if (!part.empty() && key != name) {
            if (!kept.empty()) kept += '&';
            kept += part;
        }
        pos = amp + 1;
    }
    return kept.empty() ? base + fragment : base + '?' + kept + fragment;
}

std::string appendParam(const std::string &url, const std::string &param) {
    const std::size_t hash = url.find('#');
    const std::string head = hash == std::string::npos ? url : url.substr(0, hash);
    const std::string fragment = hash == std::string::npos ? std::string() : url.substr(hash);
    const char sep = head.find('?') == std::string::npos ? '?' : '&';
    return head + sep + param + fragment;
}

std::string absolute(const std::string &url) {
    if (url.compare(0, 2, "//") == 0) return "https:" + url;
    if (!url.empty() && url[0] == '/') return "https://www.youtube.com" + url;
    return url;
}

std::string foldOrig(const std::string &code) {
    const std::string suffix = "-orig";
    if (code.size() > suffix.size() && lower(code.substr(code.size() - suffix.size())) == suffix)
        return code.substr(0, code.size() - suffix.size());
    return code;
}

bool isLiveChat(const std::string &code) { return lower(code) == "live-chat"; }

