CaptionTrackSet offeredCaptionTracks(const CaptionTrackSet &tracks) {
    if (captionTranslationsOffered()) return tracks;
    CaptionTrackSet offered;
    offered.real = tracks.real;
    return offered;
}

CaptionAutoPick autoSelectCaption(const CaptionTrackSet &tracks, const std::string &preferred) {
    CaptionAutoPick pick;
    if (preferred.empty() || lower(preferred) == kCaptionsOff) return pick;

    auto exact = [&preferred](const std::vector<CaptionTrack> &list) -> const CaptionTrack * {
        const CaptionTrack *asr = nullptr;
        for (const CaptionTrack &t : list) {
            if (!sameCode(t.code, preferred)) continue;
            if (!t.autoGenerated) return &t;
            if (!asr) asr = &t;
        }
        return asr;
    };
    const std::string base = baseLanguage(preferred);
    auto byBase = [&base](const std::vector<CaptionTrack> &list) -> const CaptionTrack * {
        const CaptionTrack *best = nullptr;
        int bestRank = 99;
        for (const CaptionTrack &t : list) {
            if (baseLanguage(t.code) != base) continue;
            const int rank = (t.autoGenerated ? 2 : 0) + (lower(t.code) == base ? 0 : 1);
            if (rank < bestRank) { best = &t; bestRank = rank; }
        }
        return best;
    };

    const CaptionTrack *t = nullptr;
    if ((t = exact(tracks.real))) pick.match = CaptionMatch::ExactReal;
    else if ((t = exact(tracks.translations))) pick.match = CaptionMatch::ExactTranslation;
    else if ((t = byBase(tracks.real))) pick.match = CaptionMatch::BaseReal;
    else if ((t = byBase(tracks.translations))) pick.match = CaptionMatch::BaseTranslation;
    if (t) pick.key = t->key;
    return pick;
}

std::string CaptionSelection::apply(const CaptionTrackSet &tracks) {
    const CaptionAutoPick p = autoSelectCaption(tracks, preferred_);
    current_ = p.key;
    match_ = p.match;
    return current_;
}

bool CaptionSelection::pick(const CaptionTrackSet &tracks, const std::string &key) {
    const CaptionTrack *t = tracks.find(key);
    if (!t) return false;
    current_ = t->key;
    match_ = CaptionMatch::None;
    if (preferred_ == t->code) return false;
    preferred_ = t->code;
    return true;
}

bool CaptionSelection::pickOff() {
    current_.clear();
    match_ = CaptionMatch::None;
    if (preferred_ == kCaptionsOff) return false;
    preferred_ = kCaptionsOff;
    return true;
}

std::string collapseWhitespace(const std::string &text) {
    std::string out;
    out.reserve(text.size());
    bool pendingSpace = false;
    for (char c : text) {
        if (isSpace(c)) { pendingSpace = !out.empty(); continue; }
        if (pendingSpace) { out += ' '; pendingSpace = false; }
        out += c;
    }
    return out;
}

std::vector<CaptionCue> buildCues(const std::vector<CaptionEvent> &events) {
    std::vector<CaptionCue> cues;
    cues.reserve(events.size());
    for (const CaptionEvent &e : events) {
        std::string text = collapseWhitespace(e.text);
        if (text.empty()) continue;
        const std::int64_t duration = e.durationMs < 0 ? kCueDefaultDurationMs : e.durationMs;
        cues.push_back(CaptionCue(e.startMs, e.startMs + duration, text));
    }
    std::stable_sort(cues.begin(), cues.end(), [](const CaptionCue &a, const CaptionCue &b) { return a.startMs < b.startMs; });

    std::vector<CaptionCue> merged;
    merged.reserve(cues.size());
    for (const CaptionCue &c : cues) {
        if (!merged.empty()) {
            CaptionCue &last = merged.back();
            if (last.text == c.text && c.startMs <= last.endMs + kCueRepeatMergeMs) {
                last.endMs = std::max(last.endMs, c.endMs);
                continue;
            }
        }
        merged.push_back(c);
    }
    for (std::size_t i = 0; i + 1 < merged.size(); ++i)
        if (merged[i].endMs > merged[i + 1].startMs) merged[i].endMs = merged[i + 1].startMs;

    std::vector<CaptionCue> out;
    out.reserve(merged.size());
    for (const CaptionCue &c : merged)
        if (c.endMs - c.startMs >= kCueMinimumMs) out.push_back(c);
    return out;
}

int cueIndexAt(const std::vector<CaptionCue> &cues, std::int64_t ms) {
    auto it = std::upper_bound(cues.begin(), cues.end(), ms,
                               [](std::int64_t v, const CaptionCue &c) { return v < c.startMs; });
    if (it == cues.begin()) return -1;
    --it;
    return ms < it->endMs ? static_cast<int>(it - cues.begin()) : -1;
}

int CueCursor::at(const std::vector<CaptionCue> &cues, std::int64_t ms) {
    const std::size_t n = cues.size();
    if (!n) { index_ = 0; return -1; }
    if (index_ > n) index_ = n;
    if (index_ > 0 && ms < cues[index_ - 1].endMs) {
        // Backward jump: every cue before the cursor ended at the last position. Rescan.
        ++rescans_;
        auto it = std::upper_bound(cues.begin(), cues.end(), ms,
                                   [](std::int64_t v, const CaptionCue &c) { return v < c.endMs; });
        index_ = static_cast<std::size_t>(it - cues.begin());
    } else {
        while (index_ < n && cues[index_].endMs <= ms) ++index_;
    }
    if (index_ < n && cues[index_].startMs <= ms && ms < cues[index_].endMs) return static_cast<int>(index_);
    return -1;
}

