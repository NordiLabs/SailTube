struct ParsedCues {
    Outcome outcome = Outcome::Network;
    CueList cues;
};

CueList emptyCues() { return std::make_shared<const std::vector<CaptionCue>>(); }

bool hasTlang(const QString &url) {
    const int q = url.indexOf(QLatin1Char('?'));
    if (q < 0) return false;
    return QUrlQuery(url.mid(q + 1)).hasQueryItem(QStringLiteral("tlang"));
}

// The json3 entry of a yt-dlp format list, else the first entry with a URL.
QJsonObject pickYtDlpEntry(const QJsonArray &entries) {
    QJsonObject first;
    for (const QJsonValue &v : entries) {
        const QJsonObject e = v.toObject();
        if (e.value(QStringLiteral("url")).toString().isEmpty()) continue;
        if (e.value(QStringLiteral("ext")).toString() == QLatin1String("json3")) return e;
        if (first.isEmpty()) first = e;
    }
    return first;
}

