CaptionService::CaptionService(HttpTransport *interactive, WorkLane *lane, QObject *parent)
    : QObject(parent), transport_(interactive), lane_(lane), cache_(kCacheUrls, 0) {}

CaptionTrackSet CaptionService::tracksFromPlayer(const QJsonObject &playerAnswer) {
    const QJsonObject list = json::at(playerAnswer, QStringLiteral("captions.playerCaptionsTracklistRenderer")).toObject();
    std::vector<CaptionSource> sources;
    for (const QJsonValue &v : list.value(QStringLiteral("captionTracks")).toArray()) {
        const QJsonObject t = v.toObject();
        CaptionSource s;
        s.url = json::s(t.value(QStringLiteral("baseUrl")).toString());
        s.languageCode = json::s(t.value(QStringLiteral("languageCode")).toString());
        s.name = json::s(json::text(t.value(QStringLiteral("name"))));
        s.autoGenerated = t.value(QStringLiteral("kind")).toString() == QLatin1String("asr");
        s.translatable = t.value(QStringLiteral("isTranslatable")).toBool(true);
        if (t.value(QStringLiteral("kind")).toString() == QLatin1String("live_chat")) continue;
        sources.push_back(s);
    }
    std::vector<CaptionLanguage> languages;
    for (const QJsonValue &v : list.value(QStringLiteral("translationLanguages")).toArray()) {
        const QJsonObject o = v.toObject();
        CaptionLanguage l;
        l.code = json::s(o.value(QStringLiteral("languageCode")).toString());
        l.name = json::s(json::text(o.value(QStringLiteral("languageName"))));
        languages.push_back(l);
    }
    return offeredCaptionTracks(shapeCaptionTracks(sources, languages));
}

CaptionTrackSet CaptionService::tracksFromYtDlp(const QJsonObject &info) {
    std::vector<CaptionSource> sources;
    auto collect = [&sources](const QJsonObject &map, bool automatic) {
        for (auto it = map.begin(); it != map.end(); ++it) {
            const QJsonObject e = pickYtDlpEntry(it.value().toArray());
            if (e.isEmpty()) continue;
            CaptionSource s;
            s.url = json::s(e.value(QStringLiteral("url")).toString());
            s.languageCode = json::s(it.key());
            s.name = json::s(e.value(QStringLiteral("name")).toString());
            s.autoGenerated = automatic;
            s.isTranslation = automatic && hasTlang(e.value(QStringLiteral("url")).toString());
            sources.push_back(s);
        }
    };
    collect(info.value(QStringLiteral("subtitles")).toObject(), false);
    collect(info.value(QStringLiteral("automatic_captions")).toObject(), true);
    return offeredCaptionTracks(shapeCaptionTracks(sources, std::vector<CaptionLanguage>()));
}

Outcome CaptionService::parseJson3(const QByteArray &body, std::vector<CaptionCue> *cues) {
    if (cues) cues->clear();
    if (body.trimmed().isEmpty()) return Outcome::Unavailable;
    QJsonParseError error;
    const QJsonDocument doc = QJsonDocument::fromJson(body, &error);
    if (error.error != QJsonParseError::NoError || !doc.isObject()) return Outcome::ShapeDrift;
    const QJsonValue eventsValue = doc.object().value(QStringLiteral("events"));
    if (!eventsValue.isArray()) {
        // A document without any event is a valid empty track only when it is a json3 shell.
        return doc.object().contains(QStringLiteral("wireMagic")) ? Outcome::ValidEmpty : Outcome::ShapeDrift;
    }
    std::vector<CaptionEvent> events;
    const QJsonArray array = eventsValue.toArray();
    events.reserve(static_cast<std::size_t>(array.size()));
    for (const QJsonValue &v : array) {
        const QJsonObject e = v.toObject();
        if (!e.contains(QStringLiteral("segs"))) continue;   // window and style events
        QString text;
        for (const QJsonValue &seg : e.value(QStringLiteral("segs")).toArray())
            text += seg.toObject().value(QStringLiteral("utf8")).toString();
        CaptionEvent ev;
        ev.startMs = static_cast<std::int64_t>(e.value(QStringLiteral("tStartMs")).toDouble());
        ev.durationMs = e.contains(QStringLiteral("dDurationMs"))
                ? static_cast<std::int64_t>(e.value(QStringLiteral("dDurationMs")).toDouble()) : -1;
        ev.text = json::s(text);
        events.push_back(ev);
    }
    std::vector<CaptionCue> built = buildCues(events);
    const bool any = !built.empty();
    if (cues) cues->swap(built);
    return any ? Outcome::Ok : Outcome::ValidEmpty;
}

bool CaptionService::isCached(const QString &url) { return cache_.contains(json::s(url)); }

quint64 CaptionService::fetchCues(const QString &url, QObject *context, std::function<void(const CueResult &)> done) {
    QPointer<QObject> guard(context);
    CueList cached;
    if (cache_.get(json::s(url), &cached)) {
        CueResult r;
        r.outcome = cached->empty() ? Outcome::ValidEmpty : Outcome::Ok;
        r.url = url;
        r.cues = cached;
        r.fromCache = true;
        QTimer::singleShot(0, this, [guard, done, r] { if (guard && done) done(r); });
        return 0;
    }

    const QUrl target(url);
    if (target.isLocalFile()) {
        // DL-07 / W4: a json3 body saved with a download, read and parsed on the lane, never fetched.
        const QString path = target.toLocalFile();
        QPointer<CaptionService> self(this);
        auto deliver = [self, guard, done, url](const ParsedCues &parsed) {
            if (!self) return;
            if (!isFailure(parsed.outcome)) self->cache_.put(json::s(url), parsed.cues);
            CueResult r;
            r.outcome = parsed.outcome;
            r.url = url;
            r.cues = parsed.cues;
            if (guard && done) done(r);
        };
        std::function<ParsedCues()> work = [path] {
            ParsedCues p;
            std::vector<CaptionCue> cues;
            QFile file(path);
            if (!file.open(QIODevice::ReadOnly)) p.outcome = Outcome::Unavailable;
            else p.outcome = parseJson3(file.readAll(), &cues);
            p.cues = std::make_shared<const std::vector<CaptionCue>>(std::move(cues));
            return p;
        };
        if (lane_) lane_->run<ParsedCues>(this, work, deliver);
        else QTimer::singleShot(0, this, [work, deliver] { deliver(work()); });
        return 0;
    }

    HttpRequest request;
    request.url = target;
    request.headers.append(qMakePair(QByteArray("User-Agent"), webUserAgent()));
    request.timeoutMs = kTimeoutMs;
    WorkLane *lane = lane_;
    QPointer<CaptionService> self(this);
    return transport_->send(request, this, [self, lane, guard, done, url](const HttpReply &http) {
        if (!self) return;
        auto deliver = [self, guard, done, url](const ParsedCues &parsed) {
            if (!self) return;
            if (self->counters_) self->counters_->count(Area::Captions, parsed.outcome);
            // Only valid answers are cached; 429, timeouts and other failures are retried next time.
            if (!isFailure(parsed.outcome)) self->cache_.put(json::s(url), parsed.cues);
            CueResult r;
            r.outcome = parsed.outcome;
            r.url = url;
            r.cues = parsed.cues;
            if (guard && done) done(r);
        };
        if (http.cancelled) return;
        if (http.timedOut || http.status < 200 || http.status >= 300) {
            ParsedCues failed;
            failed.outcome = http.timedOut ? Outcome::Network : outcomeForHttp(http.status);
            failed.cues = emptyCues();
            deliver(failed);
            return;
        }
        const QByteArray body = http.body;
        std::function<ParsedCues()> work = [body] {
            ParsedCues p;
            std::vector<CaptionCue> cues;
            p.outcome = parseJson3(body, &cues);
            p.cues = std::make_shared<const std::vector<CaptionCue>>(std::move(cues));
            return p;
        };
        if (lane) lane->run<ParsedCues>(self.data(), work, deliver);
        else deliver(work());
    });
}

void CaptionService::cancel(quint64 id) {
    if (id) transport_->cancel(id);
}

