#pragma once

// DL-07 offline extras ("sidecars") of a download: the caption tracks and the
// SponsorBlock segments saved next to it, so flight-mode playback shows
// captions and skips segments (PLY-26, SB-02 "segments are cached with
// downloads"). The catalog/playback components fetch them (SEL-06, SB-01); this
// component only stores, bounds and hands them back. Qt-free.

#include <cstddef>
#include <string>
#include <vector>

namespace nordtile { namespace video { namespace downloads {

namespace sidecarLimits {
const int maxCaptionTracks = 4;                      // per video
const std::size_t maxCaptionBytes = 4u * 1024 * 1024; // per track (json3)
const int maxSegments = 200;
const int maxAttemptsPerRun = 3;                     // fetch failures before waiting for the next start
const std::size_t maxLanguageTagChars = 16;
}

struct CaptionSidecar {
    std::string languageCode; // as given by the source ("en", "pt-BR")
    std::string name;         // display name
    bool autoGenerated = false;
    std::string file;         // file name inside the video's sidecar folder
};

struct SegmentSidecar {
    std::string category;   // sponsor, selfpromo, …, poi_highlight
    std::string actionType; // skip, mute, poi, full (as the source gives it)
    double startSeconds = 0;
    double endSeconds = 0;
};

// A file-name-safe language tag: [A-Za-z0-9-] kept, anything else '_', at most
// 16 characters; empty or all-unsafe input gives "und".
std::string safeLanguageTag(const std::string &code);

// "<tag>.json3" or "<tag>.auto.json3" for auto-generated tracks (NFR-SEC-05:
// never a separator, never a leading dot).
std::string captionFileName(const std::string &languageCode, bool autoGenerated);

// Keeps segments with a category, finite times, start >= 0 and end > start
// (poi_highlight is a point: end >= start is enough), sorted by start then
// end, at most maxSegments.
std::vector<SegmentSidecar> cleanSegments(const std::vector<SegmentSidecar> &segments);

}}}
