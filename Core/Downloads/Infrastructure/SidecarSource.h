#pragma once

// DL-07 seam for the components that fetch the offline extras of a download.
// The catalog component implements fetchCaptions from its SEL-06 track list (the
// tracks worth keeping offline: the auto-pick for the caption language and
// any explicit pick), returning the raw json3 bodies so the player's SEL-06
// parser reads them offline unchanged. fetchSegments is the SB-01 hash-prefix
// client, already filtered to this video id. The download lane calls both
// once a download is Done (and again at start-up while one is missing), on
// the main thread, and stores the results under the private data folder.
//
// Completions run on the main thread, at most once per call. ok = false means
// "try again later" (network, timeout); ok = true with an empty list is a
// final answer (no captions, SponsorBlock 404).

#include <QByteArray>
#include <QList>
#include <QString>
#include <functional>

namespace nordtile { namespace video { namespace downloads {

struct CaptionTrackData {
    QString languageCode;
    QString name;
    bool autoGenerated = false; // kind=asr
    QByteArray json3;
};

struct SkipSegmentData {
    QString category;
    QString actionType;
    double startSeconds = 0;
    double endSeconds = 0;
};

class SidecarSource {
public:
    typedef std::function<void(bool ok, const QList<CaptionTrackData> &tracks)> CaptionsDone;
    typedef std::function<void(bool ok, const QList<SkipSegmentData> &segments)> SegmentsDone;
    virtual ~SidecarSource() {}
    virtual void fetchCaptions(const QString &videoId, CaptionsDone done) = 0;
    virtual void fetchSegments(const QString &videoId, SegmentsDone done) = 0;
};

}}}
