#pragma once

// The watch session's captions seam (SEL-06, DL-07). PlaybackSession exposes captionTracks,
// captionTrackId, setCaptionTrack() and captionText to the overlay; the tracks, the auto-pick, the
// persisted explicit picks and the cues stay the catalog component's (CaptionTracksModel, CaptionCues over
// CaptionService). The session talks to them only through PlaybackCaptionSource, set from main.cpp,
// so it copies none of their logic and its host tests need none of their transports.

#include <QObject>
#include <QPointer>
#include <QString>
#include <QVariantList>
#include <functional>

namespace nordtile { namespace video { namespace sailfish {

class CaptionCues;
class CaptionTracksModel;

class PlaybackCaptionSource {
public:
    virtual ~PlaybackCaptionSource() {}
    // The tracks of `videoId`, [{id, label, language, autoGenerated, translated}] (real tracks first,
    // then translations); empty while the source holds another video's tracks or none.
    virtual QVariantList tracks(const QString &videoId) const = 0;
    // The chosen track of `videoId` ("" = off, or the source holds another video).
    virtual QString currentTrackId(const QString &videoId) const = 0;
    // An explicit pick of `videoId`'s track `id` ("" = Off); the source persists it (SEL-06). False
    // when the source holds another video or `id` is not one of its tracks.
    virtual bool select(const QString &videoId, const QString &id) = 0;
    // DL-07: a downloaded item's saved tracks ([{languageCode, name, autoGenerated, path}],
    // playback.localCaptions); the cues are read from the files, never fetched.
    virtual void setLocalTracks(const QString &videoId, const QVariantList &captions) = 0;
    // The text of the chosen track's cue at `positionMs` ("" between cues, while loading, when off).
    virtual QString textAt(qint64 positionMs) const = 0;
    // Called after any change of the tracks, the choice or the loaded cues.
    virtual void setChangedCallback(const std::function<void()> &changed) = 0;
};

// The catalog component's models behind the seam (main.cpp passes the composition's `captionTracks` and
// `captionCues`, the same objects CaptionsPage uses). The tracks model is filled by whoever knows a
// video's tracks: setFromPlayerAnswer / setFromYtDlpInfo for a stream (catalog component), setLocalTracks
// for a download (the session, from the record).
class CatalogCaptionSource final : public QObject, public PlaybackCaptionSource {
    Q_OBJECT
public:
    // Neither model is owned; both must outlive this object or be destroyed with it.
    CatalogCaptionSource(CaptionTracksModel *tracks, CaptionCues *cues, QObject *parent = nullptr);

    QVariantList tracks(const QString &videoId) const override;
    QString currentTrackId(const QString &videoId) const override;
    bool select(const QString &videoId, const QString &id) override;
    void setLocalTracks(const QString &videoId, const QVariantList &captions) override;
    QString textAt(qint64 positionMs) const override;
    void setChangedCallback(const std::function<void()> &changed) override { changed_ = changed; }

private:
    void notify();
    QPointer<CaptionTracksModel> tracks_;
    QPointer<CaptionCues> cues_;
    std::function<void()> changed_;
};

}}}
