#!/usr/bin/env python3
"""Independent golden vectors for SessionSigner and Sha1, computed with Python's hashlib.

The C++ implementation is NOT used here. Usage:
  gen_golden_vectors.py --write   regenerate golden_vectors.h
  gen_golden_vectors.py --check   fail (exit 1) if golden_vectors.h differs from a fresh computation

Construction (docs/ytm_hybrid/02-innertube-auth.md section 3.2-3.4):
  token = "<ts>_" + sha1("<ts> <cookie> <origin>")               (V1)
  V2    = up to three "<SCHEME> <ts>_<hash>" pairs joined by a space
  V3    = "<ts>_" + sha1("<session> <ts> <cookie> <origin>") + "_u"
All cookie values below are synthetic; none is a real credential.
"""
import hashlib, os, sys

ORIGIN = "https://music.youtube.com"
VECTORS = [
    # name, version, unit, seconds, extra_ms, origin, sapisid, p1, p3, session
    ("v1_seconds_basic", 1, "s", 1700000000, 0, ORIGIN, "", "", "TESTP3-aB1_cD2/eF3-gH4ij", ""),
    ("v1_seconds_sapisid_only", 1, "s", 1700000000, 0, ORIGIN, "TESTSAPISID_0123456789/abcdef-XYZ", "", "", ""),
    ("v1_both_prefers_3p", 1, "s", 1699999999, 0, ORIGIN, "TESTSAPISID_0123456789/abcdef-XYZ", "", "TESTP3-aB1_cD2/eF3-gH4ij", ""),
    ("v1_millis", 1, "ms", 1700000000, 123, ORIGIN, "", "", "TESTP3-aB1_cD2/eF3-gH4ij", ""),
    ("v1_far_future", 1, "s", 9999999999, 0, ORIGIN, "", "", "TESTP3-aB1_cD2/eF3-gH4ij", ""),
    ("v1_origin_with_port", 1, "s", 1700000000, 0, "https://music.youtube.com:8443", "", "", "TESTP3-aB1_cD2/eF3-gH4ij", ""),
    ("v1_other_origin", 1, "s", 1700000000, 0, "https://www.youtube.com", "", "", "TESTP3-aB1_cD2/eF3-gH4ij", ""),
    ("v2_triple", 2, "s", 1700000000, 0, ORIGIN, "TESTSAPISID_0123456789/abcdef-XYZ", "TESTP1_zz99-yy88_xx77/ww66", "TESTP3-aB1_cD2/eF3-gH4ij", ""),
    ("v2_only_3p", 2, "s", 1700000000, 0, ORIGIN, "", "", "TESTP3-aB1_cD2/eF3-gH4ij", ""),
    ("v2_1p_and_3p", 2, "s", 1700000000, 0, ORIGIN, "", "TESTP1_zz99-yy88_xx77/ww66", "TESTP3-aB1_cD2/eF3-gH4ij", ""),
    ("v3_user_session", 3, "s", 1700000000, 0, ORIGIN, "", "", "TESTP3-aB1_cD2/eF3-gH4ij", "sess_0001-abc"),
    ("v3_millis", 3, "ms", 1700000000, 7, ORIGIN, "TESTSAPISID_0123456789/abcdef-XYZ", "", "", "sess_0001-abc"),
]
# name, repeat, prefix  (message = prefix repeated `repeat` times)
SHA1 = [
    ("empty", 1, ""),
    ("abc", 1, "abc"),
    ("fips_448", 1, "abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq"),
    ("fips_896", 1, "abcdefghbcdefghicdefghijdefghijkefghijklfghijklmghijklmnhijklmnoijklmnopjklmnopqklmnopqrlmnopqrsmnopqrstnopqrstu"),
    ("a_x1000", 1000, "a"),
    ("z_x64", 64, "z"),
    ("block_edge_55", 55, "x"),
    ("block_edge_56", 56, "x"),
    ("block_edge_63", 63, "x"),
    ("block_edge_64", 64, "x"),
    ("block_edge_65", 65, "x"),
    ("million_a", 1000000, "a"),
]

def sign(version, unit, seconds, extra_ms, origin, sapisid, p1, p3, session):
    ts = str(seconds * 1000 + extra_ms) if unit == "ms" else str(seconds)
    h = lambda cookie, sess="": hashlib.sha1(((sess + " ") if sess else "").encode() + f"{ts} {cookie} {origin}".encode()).hexdigest()
    primary = p3 or sapisid
    if version == 1:
        return f"SAPISIDHASH {ts}_{h(primary)}"
    if version == 3:
        return f"SAPISIDHASH {ts}_{h(primary, session)}_u"
    parts = []
    first = sapisid or p3
    if first: parts.append(f"SAPISIDHASH {ts}_{h(first)}")
    if p1: parts.append(f"SAPISID1PHASH {ts}_{h(p1)}")
    if p3: parts.append(f"SAPISID3PHASH {ts}_{h(p3)}")
    return " ".join(parts)

def render():
    out = ["// GENERATED by gen_golden_vectors.py (Python hashlib, independent of the C++ code). Do not edit.",
           "#pragma once", "struct GoldenSigning { const char *name; int version; int millis; long long seconds; int extraMillis;",
           "    const char *origin, *sapisid, *p1, *p3, *session, *expected; };",
           "static const GoldenSigning kGoldenSigning[] = {"]
    for v in VECTORS:
        name, version, unit, seconds, extra, origin, sapisid, p1, p3, session = v
        exp = sign(*v[1:])
        out.append('    {"%s", %d, %d, %dLL, %d, "%s", "%s", "%s", "%s", "%s", "%s"},' %
                   (name, version, 1 if unit == "ms" else 0, seconds, extra, origin, sapisid, p1, p3, session, exp))
    out.append("};")
    out.append("struct GoldenSha1 { const char *name; unsigned long repeat; const char *prefix; const char *hex; };")
    out.append("static const GoldenSha1 kGoldenSha1[] = {")
    for name, repeat, prefix in SHA1:
        out.append('    {"%s", %dUL, "%s", "%s"},' % (name, repeat, prefix, hashlib.sha1(prefix.encode() * repeat).hexdigest()))
    out.append("};")
    return "\n".join(out) + "\n"

if __name__ == "__main__":
    here = os.path.dirname(os.path.abspath(__file__))
    path = os.path.join(here, "golden_vectors.h")
    text = render()
    if "--write" in sys.argv:
        open(path, "w").write(text); print("wrote", path)
    elif "--check" in sys.argv:
        current = open(path).read() if os.path.exists(path) else ""
        if current != text:
            print("golden_vectors.h is stale: run gen_golden_vectors.py --write"); sys.exit(1)
        print("golden vectors up to date (%d signing, %d sha1)" % (len(VECTORS), len(SHA1)))
    else:
        print(text)
