// Infrastructure-only transport; do not bind to QML or serialize in ordinary
// preferences, SQL, diagnostic messages or backups. Wiping is best effort;
// framework/provider intermediates may retain their own temporary copies.
class SecretBytes {
public:
    SecretBytes() = default;
    ~SecretBytes() { clear(); }
    SecretBytes(const SecretBytes &) = delete;
    SecretBytes &operator=(const SecretBytes &) = delete;
    SecretBytes(SecretBytes &&other) noexcept : bytes_(std::move(other.bytes_)) {}
    SecretBytes &operator=(SecretBytes &&other) noexcept {
        if (this != &other) { clear(); bytes_ = std::move(other.bytes_); } return *this;
    }
    const std::vector<unsigned char> &bytes() const { return bytes_; }
    void assign(const unsigned char *bytes, std::size_t size) { clear(); if (size) bytes_.assign(bytes, bytes + size); }
    void clear() {
        if (!bytes_.empty()) {
            volatile unsigned char *data = bytes_.data();
            for (std::size_t i = 0; i < bytes_.size(); ++i) data[i] = 0;
        }
        bytes_.clear();
    }
private:
    std::vector<unsigned char> bytes_;
};
class CredentialVaultPort {
public:
    virtual ~CredentialVaultPort() = default;
    // Synchronous worker-only calls. Opaque handle is generated by the
    // authorization adapter; it must not contain a username or token.
    virtual domain::Result store(const std::string &handle, const SecretBytes &) = 0;
    virtual domain::Result load(const std::string &handle, SecretBytes *out) = 0;
    // Intended contract (relied on by the ytm-session adapter, which also copes with an
    // implementation that fails instead): removing a handle that holds nothing is a success.
    virtual domain::Result remove(const std::string &handle) = 0;
};

