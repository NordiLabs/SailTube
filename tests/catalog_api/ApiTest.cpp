// ---------------------------------------------------------------- captions (SEL-06)

static void captions() {
    CHECK_EQ(collapseWhitespace("  Hello \n\t  world\r\n "), std::string("Hello world"));
    CHECK_EQ(collapseWhitespace(" \n\t "), std::string());
    CHECK_EQ(collapseWhitespace("one"), std::string("one"));

    CHECK(sameCode("pt_BR", "pt-br"));
    CHECK(sameCode("EN", "en"));
    CHECK(!sameCode("en", "en-GB"));
    CHECK(!sameCode("", ""));                       // an empty code never matches

    std::vector<CaptionSource> sources;
    CaptionSource manual;
    manual.url = "https://www.youtube.com/api/timedtext?v=1&lang=en&fmt=srv3";
    manual.languageCode = "en";
    manual.name = "English";
    sources.push_back(manual);
    CaptionSource manual2 = manual;
    manual2.name = "English (UK spelling)";
    sources.push_back(manual2);
    CaptionSource asr;
    asr.url = "//www.youtube.com/api/timedtext?v=1&lang=en&kind=asr";
    asr.languageCode = "en-orig";                   // yt-dlp suffix folded into the base code
    asr.autoGenerated = true;
    sources.push_back(asr);
    CaptionSource asr2 = asr;
    asr2.languageCode = "en";                       // a second ASR track of the same language: dropped
    sources.push_back(asr2);
    CaptionSource chat;
    chat.url = "https://www.youtube.com/live_chat";
    chat.languageCode = "live_chat";                // skipped
    sources.push_back(chat);
    CaptionSource ytdlp;
    ytdlp.url = "https://www.youtube.com/api/timedtext?v=1&lang=en&tlang=es&fmt=vtt";
    ytdlp.languageCode = "es";
    ytdlp.name = "Spanish";
    ytdlp.autoGenerated = true;
    ytdlp.isTranslation = true;
    sources.push_back(ytdlp);
    std::vector<CaptionLanguage> langs;
    CaptionLanguage en; en.code = "en"; en.name = "English";
    CaptionLanguage fr; fr.code = "fr"; fr.name = "French";
    langs.push_back(en);
    langs.push_back(fr);

    const CaptionTrackSet set = shapeCaptionTracks(sources, langs);
    CHECK_EQ(set.real.size(), std::size_t(3));
    if (set.real.size() == 3) {
        CHECK_EQ(set.real[0].key, std::string("en"));
        CHECK_EQ(set.real[0].url, std::string("https://www.youtube.com/api/timedtext?v=1&lang=en&fmt=json3"));
        CHECK_EQ(set.real[1].key, std::string("en#2"));
        CHECK_EQ(set.real[2].key, std::string("asr:en"));
        CHECK_EQ(set.real[2].code, std::string("en"));
        CHECK(set.real[2].autoGenerated);
        CHECK_EQ(set.real[2].url, std::string("https://www.youtube.com/api/timedtext?v=1&lang=en&kind=asr&fmt=json3"));
    }
    // "en" is dropped (a real track has it); fr comes from the ASR base, es from yt-dlp.
    CHECK_EQ(set.translations.size(), std::size_t(2));
    if (set.translations.size() == 2) {
        CHECK_EQ(set.translations[0].key, std::string("tlang:fr"));
        CHECK(set.translations[0].translation);
        CHECK_EQ(set.translations[0].url,
                 std::string("https://www.youtube.com/api/timedtext?v=1&lang=en&kind=asr&tlang=fr&fmt=json3"));
        CHECK_EQ(set.translations[1].key, std::string("tlang:es"));
        CHECK_EQ(set.translations[1].url, std::string("https://www.youtube.com/api/timedtext?v=1&lang=en&tlang=es&fmt=json3"));
    }
    CHECK(set.find("tlang:fr") != nullptr);
    CHECK(shapeCaptionTracks(std::vector<CaptionSource>(), langs).empty());   // no base track: nothing offered
}

