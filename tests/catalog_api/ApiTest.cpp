// ---------------------------------------------------------------- chapters (DSC-15)

static void chapters() {
    std::vector<ChapterMark> c;
    c.push_back(ChapterMark("Intro", 0));
    c.push_back(ChapterMark("Middle", 30));
    CHECK(validateDescriptionChapters(c, 0) == ChapterRejection::TooFew);
    c.push_back(ChapterMark("End", 60));
    CHECK(validateDescriptionChapters(c, 0) == ChapterRejection::None);      // duration unknown
    CHECK(validateDescriptionChapters(c, 61) == ChapterRejection::None);
    CHECK(validateDescriptionChapters(c, 60) == ChapterRejection::PastDuration);
    std::vector<ChapterMark> late = c;
    late[0].startSeconds = 5;
    CHECK(validateDescriptionChapters(late, 0) == ChapterRejection::FirstNotZero);
    std::vector<ChapterMark> flat = c;
    flat[2].startSeconds = 30;
    CHECK(validateDescriptionChapters(flat, 0) == ChapterRejection::NotIncreasing);
    std::vector<ChapterMark> tight = c;
    tight[2].startSeconds = 39;
    CHECK(validateDescriptionChapters(tight, 0) == ChapterRejection::GapTooSmall);

    std::vector<ChapterMark> raw;
    raw.push_back(ChapterMark("B", 60));
    raw.push_back(ChapterMark("A", 0));
    raw.push_back(ChapterMark("A again", 0));     // duplicate start: the first in order stays
    raw.push_back(ChapterMark("Bad", -5));        // negative start dropped
    raw.push_back(ChapterMark("C", 120));
    const std::vector<ChapterMark> f = finalizeChapters(raw, 200);
    CHECK_EQ(f.size(), std::size_t(3));
    if (f.size() == 3) {
        CHECK_EQ(f[0].title, std::string("A"));
        CHECK_EQ(f[0].endSeconds, std::int64_t(60));
        CHECK_EQ(f[1].title, std::string("B"));
        CHECK_EQ(f[1].endSeconds, std::int64_t(120));
        CHECK_EQ(f[2].endSeconds, std::int64_t(200));   // the last one ends at the duration
    }
    const std::vector<ChapterMark> unknown = finalizeChapters(raw, 0);
    CHECK(!unknown.empty() && unknown.back().endSeconds == -1);
    CHECK(finalizeChapters(std::vector<ChapterMark>(), 100).empty());
}

// ---------------------------------------------------------------- comments (DSC-16)

static Comment commentWithId(const std::string &id) {
    Comment c;
    c.id = id;
    c.text = "text " + id;
    return c;
}

static void comments() {
    CHECK_EQ(std::string(commentSortName(CommentSort::Newest)), std::string("newest"));
    CHECK_EQ(std::string(commentSortName(CommentSort::Top)), std::string("top"));
    CHECK(commentSortFromName("newest") == CommentSort::Newest);
    CHECK(commentSortFromName("top") == CommentSort::Top);
    CHECK(commentSortFromName("Newest") == CommentSort::Top);      // anything but "newest"
    CHECK(commentSortFromName(commentSortName(CommentSort::Newest)) == CommentSort::Newest);

    CHECK_EQ(std::string(autoLoadModeName(AutoLoadMode::Off)), std::string("off"));
    CHECK_EQ(std::string(autoLoadModeName(AutoLoadMode::Near)), std::string("near"));
    CHECK_EQ(std::string(autoLoadModeName(AutoLoadMode::AfterPlayback)), std::string("playback"));
    const AutoLoadMode modes[] = {AutoLoadMode::Off, AutoLoadMode::Near, AutoLoadMode::AfterPlayback};
    for (AutoLoadMode m : modes) CHECK(autoLoadModeFromName(autoLoadModeName(m)) == m);

    CommentBudgets budgets;
    budgets.topLevel = 2;
    CommentsSession s(budgets);
    s.reset("first");
    CHECK_EQ(s.pagesFetched(), 0);
    CHECK_EQ(s.beginRequest(), 0);
    CHECK_EQ(s.requestAdded(), 0);
    CommentsPage page;
    page.outcome = Outcome::Ok;
    page.comments.push_back(commentWithId("a"));
    page.comments.push_back(commentWithId("b"));
    page.comments.push_back(commentWithId("c"));
    page.continuation = "second";
    CHECK_EQ(s.applyThreadPage(page), 2);
    CHECK_EQ(s.requestAdded(), 2);                 // the budget is spent
    CHECK_EQ(s.pagesFetched(), 1);
    CHECK_EQ(s.bufferedThreads(), 1);
    CHECK(!s.requestNeedsAnotherPage());
    CHECK_EQ(s.beginRequest(), 1);                 // the buffered thread is handed out first
    CHECK_EQ(s.requestAdded(), 1);
    CHECK_EQ(s.threadCount(), std::size_t(3));
    CHECK(s.requestNeedsAnotherPage());            // room left and a token
    CHECK_EQ(s.applyThreadPage(page), 0);          // known ids are never added twice
    CHECK_EQ(s.pagesFetched(), 2);

    CHECK(s.scrollMayFetch());
    s.markFailed();
    CHECK(s.failed());
    CHECK(!s.scrollMayFetch());                    // a pending failure gates scrolling
    s.clearFailure();
    CHECK(!s.failed());
    CHECK(s.scrollMayFetch());
    s.markFailed();
    s.reset("other");
    CHECK(s.scrollMayFetch() && s.pagesFetched() == 0 && s.threadCount() == 0);
}

// ---------------------------------------------------------------- description text (DSC-14)

static void descriptionText() {
    std::size_t len = 0;
    CHECK_EQ(catalog::text::decodeAt("a", 0, &len), std::uint32_t('a'));
    CHECK_EQ(len, std::size_t(1));
    CHECK_EQ(catalog::text::decodeAt("x\xC3\xA9", 1, &len), std::uint32_t(0xE9));          // é
    CHECK_EQ(len, std::size_t(2));
    CHECK_EQ(catalog::text::decodeAt("\xE2\x82\xAC", 0, &len), std::uint32_t(0x20AC));     // €
    CHECK_EQ(len, std::size_t(3));
    CHECK_EQ(catalog::text::decodeAt("\xF0\x9F\x98\x80", 0, &len), std::uint32_t(0x1F600)); // emoji
    CHECK_EQ(len, std::size_t(4));
    CHECK_EQ(catalog::text::decodeAt("\x80z", 0, &len), std::uint32_t(0x80));               // invalid: itself
    CHECK_EQ(len, std::size_t(1));
    CHECK_EQ(catalog::text::decodeAt("\xC3", 0, &len), std::uint32_t(0xC3));                // truncated
    CHECK_EQ(len, std::size_t(1));
    CHECK_EQ(catalog::text::decodeAt("\xC3" "A", 0, &len), std::uint32_t(0xC3));            // bad continuation
    CHECK_EQ(len, std::size_t(1));

    CHECK(catalog::text::isWordChar('a') && catalog::text::isWordChar('Z') && catalog::text::isWordChar('7'));
    CHECK(catalog::text::isWordChar('_'));
    CHECK(!catalog::text::isWordChar('-') && !catalog::text::isWordChar(' ') && !catalog::text::isWordChar('#'));
    CHECK(catalog::text::isWordChar(0xE9));        // é
    CHECK(catalog::text::isWordChar(0x4E2D));      // 中
    CHECK(!catalog::text::isWordChar(0x2014));     // em dash
    CHECK(!catalog::text::isWordChar(0x1F600));    // emoji
    CHECK(!catalog::text::isWordChar(0xFE0F));     // VS16

    CHECK(catalog::text::isSpace(' ') && catalog::text::isSpace('\t') && catalog::text::isSpace('\n'));
    CHECK(catalog::text::isSpace(0xA0) && catalog::text::isSpace(0x3000) && catalog::text::isSpace(0x2009));
    CHECK(!catalog::text::isSpace('a') && !catalog::text::isSpace(0xE9));

    const std::string keycap = "1\xEF\xB8\x8F\xE2\x83\xA3 Intro";   // 1 VS16 U+20E3
    CHECK_EQ(catalog::text::keycapAt(keycap, 0), std::size_t(7));
    CHECK_EQ(catalog::text::keycapAt("#\xE2\x83\xA3", 0), std::size_t(4));   // without VS16
    CHECK_EQ(catalog::text::keycapAt("x 2\xE2\x83\xA3", 2), std::size_t(4));
    CHECK_EQ(catalog::text::keycapAt("1 Intro", 0), std::size_t(0));
    CHECK_EQ(catalog::text::keycapAt("a\xE2\x83\xA3", 0), std::size_t(0));
    CHECK_EQ(catalog::text::keycapAt("1", 5), std::size_t(0));

    std::vector<DescriptionRun> runs;
    runs.push_back(DescriptionRun(RunKind::Text, "Hello "));
    runs.push_back(DescriptionRun(RunKind::Text, ""));
    runs.push_back(DescriptionRun(RunKind::Text, "there "));
    DescriptionRun link(RunKind::Link, "example.com");
    link.url = "https://example.com";
    runs.push_back(link);
    runs.push_back(DescriptionRun(RunKind::Link, ""));          // empty: dropped whatever its kind
    runs.push_back(DescriptionRun(RunKind::Text, " and"));
    runs.push_back(DescriptionRun(RunKind::Text, " more"));
    const std::vector<DescriptionRun> merged = mergeTextRuns(runs);
    CHECK_EQ(merged.size(), std::size_t(3));
    if (merged.size() == 3) {
        CHECK(merged[0].kind == RunKind::Text);
        CHECK_EQ(merged[0].text, std::string("Hello there "));
        CHECK(merged[1].kind == RunKind::Link);
        CHECK_EQ(merged[1].url, std::string("https://example.com"));
        CHECK_EQ(merged[2].text, std::string(" and more"));
    }
    CHECK_EQ(runsText(merged), runsText(runs));     // merging never changes the text
    CHECK(mergeTextRuns(std::vector<DescriptionRun>()).empty());
}

// ---------------------------------------------------------------- clocks and caches

static void clocksAndCaches() {
    const std::int64_t a = steadyMillis();
    const std::int64_t b = steadyMillis();
    CHECK(b >= a);                                  // monotonic
    CHECK(std::llabs(static_cast<long long>(steadyMillis() - chronoSteadyMs())) < 1000);
    const std::int64_t c = steadyNowMs();
    CHECK(steadyNowMs() >= c);
    CHECK(std::llabs(static_cast<long long>(steadyNowMs() - chronoSteadyMs())) < 1000);

    std::int64_t now = 100;
    ExpiringLru<int> lru(4, 1000, [&now] { return now; });
    lru.put("a", 1);
    CHECK_EQ(lru.ageMs("a"), std::int64_t(0));
    now = 350;
    CHECK_EQ(lru.ageMs("a"), std::int64_t(250));
    CHECK_EQ(lru.ageMs("missing"), std::int64_t(-1));
    lru.put("a", 2);                                // replacing restarts the lifetime
    CHECK_EQ(lru.ageMs("a"), std::int64_t(0));

    now = 0;
    TtlLruCache<int> ttl([&now] { return now; }, 100, 4);
    ttl.put("a", std::make_shared<int>(1));
    ttl.put("b", std::make_shared<int>(2));
    now = 90;
    ttl.restamp("a");                               // a completed refresh: life starts again
    ttl.restamp("unknown");                         // no-op
    CHECK_EQ(ttl.size(), std::size_t(2));
    now = 150;
    CHECK(ttl.get("a") != nullptr);                 // 60 ms since the restamp
    CHECK(ttl.get("b") == nullptr);                 // 150 ms old: expired
    CHECK(ttl.fresh("a"));
    now = 190;
    CHECK(!ttl.fresh("a"));
}

// ---------------------------------------------------------------- feed schedule (DSC-05/06)

static Item feedRow(const std::string &id, std::int64_t epoch) {
    Item it;
    it.id = id;
    it.publishedEpoch = epoch;
    it.liveStatus = media::LiveStatus::NotLive;
    return it;
}

static void feedSchedule() {
    ChannelFeedState state(ChannelRef(kNasa, "NASA"));
    CHECK_EQ(newestUploadEpoch(state), std::int64_t(-1));       // no rows
    state.fetchedAt = 1000;
    state.rows.push_back(feedRow("aaaaaaaaaaa", 500));
    Item aged = feedRow("bbbbbbbbbbb", -1);
    aged.publishedAgeSeconds = 100;                               // fetched at 1000 -> 900
    state.rows.push_back(aged);
    Item upcoming = feedRow("ccccccccccc", 5000);
    upcoming.liveStatus = media::LiveStatus::Upcoming;            // never counts as an upload
    state.rows.push_back(upcoming);
    CHECK_EQ(newestUploadEpoch(state), std::int64_t(900));
    Item running = feedRow("ddddddddddd", -1);
    running.liveStatus = media::LiveStatus::IsLive;               // counts at fetch time
    state.rows.push_back(running);
    CHECK_EQ(newestUploadEpoch(state), std::int64_t(1000));

    ChannelFeedState fresh(ChannelRef(kNasa, "NASA"));
    CHECK_EQ(dueAt(fresh, 5000), std::int64_t(5000));             // never attempted: due now
    fresh.lastAttemptAt = 10000000;
    CHECK_EQ(dueAt(fresh, 20000000), std::int64_t(10000000 + kEmptyChannelRetrySeconds));   // no rows: hourly
    CHECK_EQ(dueAt(fresh, 5000000), std::int64_t(5000000));       // the clock went back
    fresh.fetchedAt = 10000000;
    fresh.rows.push_back(feedRow("eeeeeeeeeee", 10000000 - kFeedDay));   // newest upload a day old
    CHECK_EQ(dueAt(fresh, 10000000), std::int64_t(10000000 + 10 * kFeedMinute));
    fresh.rows.back().publishedEpoch = 10000000 - 30 * kFeedDay;   // a month old: every 6 h
    CHECK_EQ(dueAt(fresh, 10000000), std::int64_t(10000000 + 6 * kFeedHour));

    CHECK(isMalformedFeedRow(feedRow("", 100), 1000));            // no id
    Item channelRow = feedRow("UCxxxxxxxxxxxxxxxxxxxxxx", 100);
    channelRow.kind = ItemKind::Channel;
    CHECK(isMalformedFeedRow(channelRow, 1000));                  // not a video
    CHECK(isMalformedFeedRow(feedRow("fffffffffff", -1), 1000));  // no timestamp
    CHECK(!isMalformedFeedRow(feedRow("fffffffffff", 100), 1000));
    Item soon = feedRow("ggggggggggg", -1);
    soon.liveStatus = media::LiveStatus::Upcoming;
    CHECK(!isMalformedFeedRow(soon, 1000));                       // sorts at its fetch time
    CHECK(isMalformedFeedRow(soon, -1));

    std::int64_t now = 10000;
    FeedSchedule schedule([&now] { return now; });
    CHECK(!schedule.anyDue());                                    // no channels
    ChannelList list;
    list.push_back(ChannelRef(kNasa, "NASA"));
    schedule.setChannels(list);
    CHECK(schedule.anyDue());                                     // new channels are due at once
    schedule.markAttempt(kNasa);
    CHECK_EQ(schedule.find(kNasa)->lastAttemptAt, now);
    CHECK(!schedule.anyDue());
    schedule.markAttempt("UCunknownunknownunknown0");             // unknown: ignored
    now += kEmptyChannelRetrySeconds - 1;
    CHECK(!schedule.anyDue());
    now += 1;
    CHECK(schedule.anyDue());                                     // an hour later without rows

    ChannelList all;
    all.push_back(ChannelRef(kNasa, "NASA"));
    all.push_back(ChannelRef("not-a-channel", "Bad"));
    all.push_back(ChannelRef("UCsXVk37bltHxD1rDPwtNM8Q", "Kurzgesagt"));
    all.push_back(ChannelRef(kNasa, "NASA again"));
    all.push_back(ChannelRef("@handle", "Handle"));
    const ChannelList feed = feedChannels(all);
    CHECK_EQ(feed.size(), std::size_t(2));
    if (feed.size() == 2) {
        CHECK_EQ(feed[0].id, std::string(kNasa));
        CHECK_EQ(feed[0].name, std::string("NASA"));             // first occurrence wins
        CHECK_EQ(feed[1].id, std::string("UCsXVk37bltHxD1rDPwtNM8Q"));
    }
    CHECK(feedChannels(ChannelList()).empty());
}

