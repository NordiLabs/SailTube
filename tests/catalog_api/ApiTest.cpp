static void jsonHelpers() {
    const QJsonObject tree = parseObject("{\"a\":{\"b\":[{\"c\":1},{\"d\":{\"e\":true}}]}}");
    CHECK(json::containsKey(tree, QStringList() << QStringLiteral("c")));
    CHECK(json::containsKey(tree, QStringList() << QStringLiteral("e")));            // deep inside an array
    CHECK(json::containsKey(tree, QStringList() << QStringLiteral("x") << QStringLiteral("b")));
    CHECK(!json::containsKey(tree, QStringList() << QStringLiteral("x")));
    CHECK(!json::containsKey(QJsonObject(), QStringList() << QStringLiteral("a")));

    const QJsonObject thumbs = parseObject(
        "{\"thumbnails\":[{\"url\":\"//i.ytimg.com/m.jpg\",\"width\":320},"
        "{\"url\":\"https://i.ytimg.com/l.jpg\",\"width\":480},{\"url\":\"//i.ytimg.com/s.jpg\",\"width\":120}]}");
    CHECK_EQ(json::bestImage(thumbs), QStringLiteral("https://i.ytimg.com/l.jpg"));
    CHECK_EQ(json::bestImage(thumbs, false), QStringLiteral("https://i.ytimg.com/s.jpg"));   // made absolute
    const QJsonObject sources = parseObject("{\"sources\":[{\"url\":\"//yt3.ggpht.com/a\",\"width\":68},{\"url\":\"//yt3.ggpht.com/b\",\"width\":176}]}");
    CHECK_EQ(json::bestImage(sources), QStringLiteral("https://yt3.ggpht.com/b"));
    const QJsonObject image = parseObject("{\"image\":{\"sources\":[{\"url\":\"https://yt3.ggpht.com/c\",\"width\":72}]}}");
    CHECK_EQ(json::bestImage(image), QStringLiteral("https://yt3.ggpht.com/c"));
    CHECK(json::bestImage(QJsonObject()).isEmpty());

    const QJsonObject byline = parseObject(
        "{\"runs\":[{\"text\":\"NASA\",\"navigationEndpoint\":{\"browseEndpoint\":{\"browseId\":\"UCLA_DiR1FfKNvjuUpBHmylQ\"}}},"
        "{\"text\":\"Other\",\"navigationEndpoint\":{\"browseEndpoint\":{\"browseId\":\"UCsXVk37bltHxD1rDPwtNM8Q\"}}}]}");
    CHECK_EQ(json::firstBrowseId(byline), QString::fromLatin1(kNasa));                  // the first one
    CHECK(json::firstBrowseId(parseObject("{\"runs\":[{\"text\":\"plain\"}]}")).isEmpty());
}

