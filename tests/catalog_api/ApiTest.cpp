    CHECK_EQ(pl.id, std::string("PLabcdefgh"));
    CHECK_EQ(pl.title, std::string("Missions"));
    CHECK_EQ(pl.channel, std::string("NASA"));
    CHECK_EQ(pl.channelId, std::string(kNasa));
    CHECK_EQ(pl.videoCount, std::int64_t(27));
    CHECK_EQ(pl.thumbnailUrl, std::string("https://i.ytimg.com/small.jpg"));
