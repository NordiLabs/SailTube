// ---------------------------------------------------------------- Shorts (DSC-17)

static void shorts() {
    Item row;
    row.id = "abcdefghijk";
    row.kind = ItemKind::Video;
    row.durationSeconds = 60;
    row.liveStatus = media::LiveStatus::NotLive;
    const ShortsLookup none;
    CHECK(effectiveShortEvidence(row, none) == ShortEvidence::Candidate);          // the 180 s rule
    const ShortsLookup knowsTab = [](const std::string &id) {
        return id == "abcdefghijk" ? ShortEvidence::ShortsTab : ShortEvidence::None;
    };
    CHECK(effectiveShortEvidence(row, knowsTab) == ShortEvidence::ShortsTab);      // the store beats the rule
    const ShortsLookup blank = [](const std::string &) { return ShortEvidence::None; };
    CHECK(effectiveShortEvidence(row, blank) == ShortEvidence::Candidate);
    Item structural = row;
    structural.shortEvidence = ShortEvidence::Renderer;
    const ShortsLookup saysNot = [](const std::string &) { return ShortEvidence::NotShort; };
    CHECK(effectiveShortEvidence(structural, saysNot) == ShortEvidence::Renderer); // the row wins
    Item checked = row;
    checked.shortEvidence = ShortEvidence::NotShort;
    CHECK(effectiveShortEvidence(checked, knowsTab) == ShortEvidence::NotShort);
    Item longer = row;
    longer.durationSeconds = kShortCandidateMaxSeconds + 1;
    CHECK(effectiveShortEvidence(longer, none) == ShortEvidence::None);
    Item edge = row;
    edge.durationSeconds = kShortCandidateMaxSeconds;
    CHECK(effectiveShortEvidence(edge, none) == ShortEvidence::Candidate);
    Item live = row;
    live.liveStatus = media::LiveStatus::IsLive;
    CHECK(effectiveShortEvidence(live, none) == ShortEvidence::None);
    Item unknownLength = row;
    unknownLength.durationSeconds = -1;
    CHECK(effectiveShortEvidence(unknownLength, none) == ShortEvidence::None);

    std::int64_t now = 1000;
    ShortsKnowledge k([&now] { return now; });
    CHECK_EQ(k.notShortCount(), std::size_t(0));
    k.markNotShort("abcdefghijk");
    k.markNotShort("bad");                          // not a video id: ignored
    CHECK_EQ(k.notShortCount(), std::size_t(1));
    CHECK(k.notShorts().contains("abcdefghijk"));
    CHECK(k.evidence("abcdefghijk") == ShortEvidence::NotShort);
    k.markShort("abcdefghijk", ShortEvidence::RssLink);   // confirmed evidence overrides "not a Short"
    CHECK_EQ(k.notShortCount(), std::size_t(0));
    CHECK(!k.notShorts().contains("abcdefghijk"));
    k.markNotShort("abcdefghijk");                  // never overrides a known Short
    CHECK_EQ(k.notShortCount(), std::size_t(0));
    CHECK(k.evidence("abcdefghijk") == ShortEvidence::RssLink);

    CHECK(!k.recentlyChecked(kNasa));
    k.noteChecked(kNasa);
    CHECK(k.recentlyChecked(kNasa));
    now += ShortsKnowledge::kRecheckIntervalMs - 1;
    CHECK(k.recentlyChecked(kNasa));
    now += 1;
    CHECK(!k.recentlyChecked(kNasa));               // 30 min later the channel may be checked again
}

