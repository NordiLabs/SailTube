static void cachedItems() {
    Item it;
    it.kind = ItemKind::Short;
    it.id = "k5Z7sFwFF7Q";
    it.title = "Become a NASA Astronaut!";
    it.channel = "NASA";
    it.channelId = kNasa;
    it.durationSeconds = 59;
    it.durationText = "0:59";
    it.viewCount = 22000;
    it.viewText = "22K views";
    it.publishedEpoch = 1794000000;
    it.publishedAgeSeconds = 86400;
    it.publishedText = "1 day ago";
    it.thumbnailUrl = listThumbnailUrl(it.id);
    it.liveStatus = media::LiveStatus::WasLive;
    it.membersOnly = true;
    it.restricted = true;
    it.shortEvidence = ShortEvidence::RssLink;
    const QJsonObject o = cachedItemToJson(it);
    CHECK_EQ(o.value(QStringLiteral("id")).toString(), QStringLiteral("k5Z7sFwFF7Q"));
    const Item back = cachedItemFromJson(o);
    CHECK(back.kind == ItemKind::Short);
    CHECK_EQ(back.id, it.id);
    CHECK_EQ(back.title, it.title);
    CHECK_EQ(back.channel, it.channel);
    CHECK_EQ(back.channelId, it.channelId);
    CHECK_EQ(back.durationSeconds, it.durationSeconds);
    CHECK_EQ(back.durationText, it.durationText);
    CHECK_EQ(back.viewCount, it.viewCount);
    CHECK_EQ(back.viewText, it.viewText);
    CHECK_EQ(back.publishedEpoch, it.publishedEpoch);
    CHECK_EQ(back.publishedAgeSeconds, it.publishedAgeSeconds);
    CHECK_EQ(back.publishedText, it.publishedText);
    CHECK_EQ(back.thumbnailUrl, it.thumbnailUrl);
    CHECK(back.liveStatus == media::LiveStatus::WasLive);
    CHECK(back.membersOnly && back.restricted);
    CHECK(back.shortEvidence == ShortEvidence::RssLink);

    // Compact: unknown values are left out and come back as unknown.
    Item bare;
    bare.id = "aaaaaaaaaaa";
    const QJsonObject b = cachedItemToJson(bare);
    CHECK(!b.contains(QStringLiteral("c")) && !b.contains(QStringLiteral("d")) && !b.contains(QStringLiteral("se")));
    const Item bareBack = cachedItemFromJson(b);
    CHECK_EQ(bareBack.durationSeconds, std::int64_t(-1));
    CHECK_EQ(bareBack.viewCount, std::int64_t(-1));
    CHECK(bareBack.liveStatus == media::LiveStatus::Unknown);
    CHECK(bareBack.shortEvidence == ShortEvidence::None);
    // Out-of-range enum values fall back instead of producing an invalid enum.
    QJsonObject bad = b;
    bad.insert(QStringLiteral("k"), 99);
    bad.insert(QStringLiteral("ls"), 99);
    bad.insert(QStringLiteral("se"), -3);
    const Item badBack = cachedItemFromJson(bad);
    CHECK(badBack.kind == ItemKind::Video);
    CHECK(badBack.liveStatus == media::LiveStatus::Unknown);
    CHECK(badBack.shortEvidence == ShortEvidence::None);
}

