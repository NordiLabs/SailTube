static void sponsorSegments() {
    std::vector<SponsorPrefixEntry> answer;
    SponsorPrefixEntry other;
    other.videoId = "zzzzzzzzzzz";                  // shares the prefix, another video
    other.segments.push_back(SponsorSegment(1, 2, "sponsor"));
    answer.push_back(other);
    SponsorPrefixEntry mine;
    mine.videoId = "9zCH37330f8";
    mine.segments.push_back(SponsorSegment(10, 20, "sponsor"));
    mine.segments.push_back(SponsorSegment(5, 8, "selfpromo"));
    mine.segments.push_back(SponsorSegment(5, 6, "intro"));
    mine.segments.push_back(SponsorSegment(1, 3, "chapter"));         // not a skip category
    mine.segments.push_back(SponsorSegment(30, 30, "sponsor"));       // zero length
    mine.segments.push_back(SponsorSegment(40, 35, "outro"));         // end before start
    mine.segments.push_back(SponsorSegment(42, 42, kSponsorHighlightCategory));
    mine.segments.push_back(SponsorSegment(50, 50, kSponsorHighlightCategory));   // only the first one
    answer.push_back(mine);
    const SponsorSegmentList list = filterSponsorSegments(answer, "9zCH37330f8");
    CHECK_EQ(list.segments.size(), std::size_t(3));
    if (list.segments.size() == 3) {
        CHECK_EQ(list.segments[0].category, std::string("intro"));    // start 5, end 6
        CHECK_EQ(list.segments[1].category, std::string("selfpromo")); // start 5, end 8
        CHECK_EQ(list.segments[2].category, std::string("sponsor"));
        CHECK(list.segments[2].startSeconds == 10 && list.segments[2].endSeconds == 20);
    }
    CHECK(list.hasHighlight);
    CHECK(list.highlightSeconds == 42);
    const SponsorSegmentList nothing = filterSponsorSegments(answer, "aaaaaaaaaaa");
    CHECK(nothing.segments.empty() && !nothing.hasHighlight);
}

