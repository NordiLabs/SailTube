static int failures = 0;
#define CHECK(c) do { if (!(c)) { std::printf("FAIL %s:%d: %s\n", __FILE__, __LINE__, #c); ++failures; } } while (0)

static void spin(int ms) {
    QEventLoop loop;
    QTimer::singleShot(ms, &loop, SLOT(quit()));
    loop.exec();
}

static CaptionTrackData track(const char *lang, bool asr, const QByteArray &body = QByteArray("{\"events\":[]}")) {
    CaptionTrackData t;
    t.languageCode = QString::fromUtf8(lang);
    t.name = QStringLiteral("Name ") + t.languageCode;
    t.autoGenerated = asr;
    t.json3 = body;
    return t;
}

static SkipSegmentData segment(const char *category, double start, double end) {
    SkipSegmentData s;
    s.category = QString::fromLatin1(category);
    s.actionType = QStringLiteral("skip");
    s.startSeconds = start;
    s.endSeconds = end;
    return s;
}

// Answers after `delayMs` (0 = synchronously) with the configured result.
class FakeSource final : public SidecarSource {
public:
    void fetchCaptions(const QString &videoId, CaptionsDone done) override {
        captionCalls << videoId;
        const bool ok = captionsOk;
        const QList<CaptionTrackData> tracks = captions;
        if (delayMs == 0) { done(ok, tracks); return; }
        QTimer::singleShot(delayMs, [done, ok, tracks]() { done(ok, tracks); });
    }
    void fetchSegments(const QString &videoId, SegmentsDone done) override {
        segmentCalls << videoId;
        const bool ok = segmentsOk;
        const QList<SkipSegmentData> list = segments;
        if (delayMs == 0) { done(ok, list); return; }
        QTimer::singleShot(delayMs, [done, ok, list]() { done(ok, list); });
    }
    QStringList captionCalls, segmentCalls;
    bool captionsOk = true, segmentsOk = true;
    QList<CaptionTrackData> captions;
    QList<SkipSegmentData> segments;
    int delayMs = 0;
};

class PendingResolver final : public DownloadResolver {
public:
    quint64 resolve(const QString &, Completion) override { return ++next; }
    void cancel(quint64) override {}
    quint64 next = 0;
};

static void domainTests() {
    CHECK(safeLanguageTag("en") == "en");
    CHECK(safeLanguageTag("pt-BR") == "pt-BR");
    CHECK(safeLanguageTag("../x") == "___x");
    CHECK(safeLanguageTag("") == "und");
    CHECK(safeLanguageTag("\xe6\x97\xa5\xe6\x9c\xac") == "und");
    CHECK(safeLanguageTag("abcdefghijklmnopqrstuvwxyz").size() == 16);
    CHECK(captionFileName("en", false) == "en.json3");
    CHECK(captionFileName("en", true) == "en.auto.json3");
    CHECK(captionFileName("../../etc/passwd", false).find('/') == std::string::npos);
    CHECK(captionFileName(".hidden", false)[0] != '.');

    std::vector<SegmentSidecar> in;
    SegmentSidecar s;
    s.category = "outro"; s.startSeconds = 300; s.endSeconds = 320; in.push_back(s);
    s.category = "sponsor"; s.startSeconds = 10; s.endSeconds = 40; in.push_back(s);
    s.category = "sponsor"; s.startSeconds = 50; s.endSeconds = 50; in.push_back(s);        // end == start
    s.category = "intro"; s.startSeconds = 60; s.endSeconds = 55; in.push_back(s);          // end < start
    s.category = "selfpromo"; s.startSeconds = -1; s.endSeconds = 5; in.push_back(s);       // negative
    s.category = ""; s.startSeconds = 1; s.endSeconds = 5; in.push_back(s);                 // no category
    s.category = "filler"; s.startSeconds = std::numeric_limits<double>::quiet_NaN(); s.endSeconds = 5; in.push_back(s);
    s.category = "poi_highlight"; s.startSeconds = 100; s.endSeconds = 100; in.push_back(s); // a point
    s.category = "sponsor"; s.startSeconds = 10; s.endSeconds = 20; in.push_back(s);
    const std::vector<SegmentSidecar> out = cleanSegments(in);
    CHECK(out.size() == 4);
    if (out.size() == 4) {
        CHECK(out[0].startSeconds == 10 && out[0].endSeconds == 20);
        CHECK(out[1].startSeconds == 10 && out[1].endSeconds == 40);
        CHECK(out[2].category == "poi_highlight");
        CHECK(out[3].category == "outro");
    }
    std::vector<SegmentSidecar> many;
    for (int i = 0; i < 250; ++i) { s.category = "sponsor"; s.startSeconds = 250 - i; s.endSeconds = 251 - i; many.push_back(s); }
    const std::vector<SegmentSidecar> capped = cleanSegments(many);
    CHECK(capped.size() == static_cast<std::size_t>(sidecarLimits::maxSegments));
    CHECK(capped.front().startSeconds == 1);
}

static void storeTests(const QString &root) {
    const QString vid = QStringLiteral("aaaaaaaaaaa");
    FakeSource source;
    source.captions << track("en", false) << track("en", true) << track("es", false);
    source.segments << segment("outro", 300, 320) << segment("sponsor", 10, 40) << segment("intro", 60, 55);
    {
        SidecarStore store(root);
        QStringList changed;
        QObject::connect(&store, &SidecarStore::changed, [&changed](const QString &id) { changed << id; });
        CHECK(store.pending(vid)); // wanted, not saved yet
        store.ensure(vid);          // no source: nothing happens
        CHECK(store.pending(vid));
        store.setSource(&source);
        store.ensure(vid);
        CHECK(source.captionCalls.size() == 1 && source.segmentCalls.size() == 1);
        CHECK(changed.count(vid) == 2);
        const QVariantMap info = store.info(vid);
        CHECK(!info.value(QStringLiteral("pending")).toBool());
        const QVariantList captions = info.value(QStringLiteral("captions")).toList();
        CHECK(captions.size() == 3);
        for (const QVariant &c : captions) {
            const QString path = c.toMap().value(QStringLiteral("path")).toString();
            CHECK(QFileInfo(path).isFile());
            CHECK(path.startsWith(root + QLatin1Char('/')));
            CHECK((QFile::permissions(path) & (QFileDevice::ReadGroup | QFileDevice::ReadOther)) == 0);
        }
        CHECK(captions.value(1).toMap().value(QStringLiteral("autoGenerated")).toBool());
        CHECK(captions.value(1).toMap().value(QStringLiteral("path")).toString().endsWith(QStringLiteral("/en.auto.json3")));
        const QVariantList segments = info.value(QStringLiteral("segments")).toList();
        CHECK(segments.size() == 2);
        CHECK(segments.value(0).toMap().value(QStringLiteral("category")).toString() == QStringLiteral("sponsor"));
        CHECK(segments.value(0).toMap().value(QStringLiteral("start")).toDouble() == 10);
        CHECK(segments.value(1).toMap().value(QStringLiteral("end")).toDouble() == 320);
        const QString index = root + QStringLiteral("/aaaaaaaaaaa/index.json");
        CHECK(QFileInfo(index).isFile());
        CHECK((QFile::permissions(index) & (QFileDevice::ReadGroup | QFileDevice::ReadOther)) == 0);
        store.ensure(vid); // complete: no second fetch
        CHECK(source.captionCalls.size() == 1 && source.segmentCalls.size() == 1);
    }
    {
        // a restart reads the saved extras back and fetches nothing
        SidecarStore store(root);
        store.setSource(&source);
        store.ensure(vid);
        CHECK(source.captionCalls.size() == 1 && source.segmentCalls.size() == 1);
        const QVariantMap info = store.info(vid);
        CHECK(info.value(QStringLiteral("captions")).toList().size() == 3);
        CHECK(info.value(QStringLiteral("segments")).toList().size() == 2);
        CHECK(!info.value(QStringLiteral("pending")).toBool());
        // a caption file that vanished drops that track only
        QFile::remove(root + QStringLiteral("/aaaaaaaaaaa/es.json3"));
        SidecarStore again(root);
        CHECK(again.info(vid).value(QStringLiteral("captions")).toList().size() == 2);
        // removing the video deletes its folder
        store.remove(vid);
        CHECK(!QFileInfo(root + QStringLiteral("/aaaaaaaaaaa")).exists());
        CHECK(store.info(vid).value(QStringLiteral("captions")).toList().isEmpty());
    }

    // failures: the extra stays pending, at most 3 attempts per run, the next run tries again
    const QString b = QStringLiteral("bbbbbbbbbbb");
    FakeSource flaky;
    flaky.captionsOk = false;
    flaky.segmentsOk = false;
    {
        SidecarStore store(root);
        store.setSource(&flaky);
        for (int i = 0; i < 5; ++i) store.ensure(b);
        CHECK(flaky.captionCalls.size() == sidecarLimits::maxAttemptsPerRun);
        CHECK(flaky.segmentCalls.size() == sidecarLimits::maxAttemptsPerRun);
        CHECK(store.pending(b));
    }
    {
        SidecarStore store(root);
        flaky.captionsOk = true;  // captions now answer "none" (final), segments still fail
        store.setSource(&flaky);
        store.ensure(b);
        CHECK(flaky.captionCalls.size() == sidecarLimits::maxAttemptsPerRun + 1);
        const QVariantMap info = store.info(b);
        CHECK(info.value(QStringLiteral("captionsSaved")).toBool());
        CHECK(info.value(QStringLiteral("captions")).toList().isEmpty());
        CHECK(!info.value(QStringLiteral("segmentsSaved")).toBool());
        CHECK(info.value(QStringLiteral("pending")).toBool());
        flaky.segmentsOk = true; // SponsorBlock 404: ok with no segments is final
        store.ensure(b);
        CHECK(!store.pending(b));
        store.ensure(b);
        CHECK(flaky.captionCalls.size() == sidecarLimits::maxAttemptsPerRun + 1);
    }

    // bounds and names: 4 tracks at most, oversize and empty bodies skipped,
    // duplicate languages kept once, hostile codes and ids stay inside the root
    const QString c = QStringLiteral("../../evil");
    FakeSource bulky;
    bulky.captions << track("de", false, QByteArray(static_cast<int>(sidecarLimits::maxCaptionBytes) + 1, 'x'))
                   << track("fr", false, QByteArray())
                   << track("en", false) << track("en", false) << track("../../etc/passwd", false)
                   << track("ja", true) << track("ko", false) << track("zh", false);
    {
        SidecarStore store(root);
        store.setSource(&bulky);
        store.ensure(c);
        const QVariantList captions = store.info(c).value(QStringLiteral("captions")).toList();
        CHECK(captions.size() == sidecarLimits::maxCaptionTracks);
        QStringList names;
        for (const QVariant &v : captions) {
            const QString path = v.toMap().value(QStringLiteral("path")).toString();
            CHECK(QFileInfo(path).absolutePath().startsWith(QFileInfo(root).absoluteFilePath() + QLatin1Char('/')));
            CHECK(QFileInfo(path).isFile());
            names << QFileInfo(path).fileName();
        }
        CHECK(names.contains(QStringLiteral("en.json3")) && names.count(QStringLiteral("en.json3")) == 1);
        CHECK(!names.contains(QStringLiteral("de.json3")) && !names.contains(QStringLiteral("fr.json3")));
        CHECK(!QFileInfo(QFileInfo(root).absolutePath() + QStringLiteral("/evil")).exists());
        store.remove(c);
    }

    // turned off: nothing fetched, nothing pending
    const QString d = QStringLiteral("ddddddddddd");
    FakeSource unused;
    {
        SidecarStore store(root);
        store.setSource(&unused);
        CHECK(store.captionsWanted() && store.segmentsWanted()); // default on
        store.setWanted(false, false);
        CHECK(!store.captionsWanted() && !store.segmentsWanted());
        store.ensure(d);
        CHECK(unused.captionCalls.isEmpty() && unused.segmentCalls.isEmpty());
        CHECK(!store.pending(d));
        store.setWanted(false, true);
        store.ensure(d);
        CHECK(unused.captionCalls.isEmpty() && unused.segmentCalls.size() == 1);
    }

    // removed while a fetch is in flight: the late answer is discarded
    const QString e = QStringLiteral("eeeeeeeeeee");
    FakeSource slow;
    slow.delayMs = 50;
    slow.captions << track("en", false);
    slow.segments << segment("sponsor", 1, 2);
    {
        SidecarStore store(root);
        store.setSource(&slow);
        store.ensure(e);
        store.ensure(e); // in flight: no second request
        CHECK(slow.captionCalls.size() == 1);
        store.remove(e);
        spin(150);
        CHECK(!QFileInfo(root + QStringLiteral("/eeeeeeeeeee")).exists());
        CHECK(store.info(e).value(QStringLiteral("captions")).toList().isEmpty());
        store.ensure(e); // a new download of it fetches again
        spin(150);
        CHECK(store.info(e).value(QStringLiteral("captions")).toList().size() == 1);
    }
}

// An index written before version 2 that recorded "no captions" is asked again once (that request
// could not see the tracks); one that kept captions is left alone; the new answer is final.
static void oldIndexTests(const QString &root) {
    const auto writeIndex = [&root](const QString &vid, int version, const QByteArray &captions) {
        QDir().mkpath(root + QLatin1Char('/') + vid);
        QFile f(root + QLatin1Char('/') + vid + QStringLiteral("/index.json"));
        CHECK(f.open(QIODevice::WriteOnly));
        f.write("{\"version\":" + QByteArray::number(version) + ",\"videoId\":\"" + vid.toLatin1()
                + "\",\"captionsSaved\":true,\"segmentsSaved\":true,\"captions\":" + captions + ",\"segments\":[]}");
    };
    const QString none = QStringLiteral("oldnone0001"), kept = QStringLiteral("oldkept0001"), current = QStringLiteral("newnone0001");
    writeIndex(none, 1, "[]");
    writeIndex(kept, 1, "[{\"languageCode\":\"en\",\"name\":\"English\",\"autoGenerated\":false,\"file\":\"en.json3\"}]");
    { QFile f(root + QLatin1Char('/') + kept + QStringLiteral("/en.json3")); CHECK(f.open(QIODevice::WriteOnly)); f.write("{\"events\":[]}"); }
    writeIndex(current, 2, "[]");
    FakeSource source;
    source.captions << track("en", false);
    {
        SidecarStore store(root);
        store.setSource(&source);
        CHECK(store.pending(none));
        CHECK(!store.pending(kept));
        CHECK(!store.pending(current));     // a version 2 "none" is final
        store.ensure(none);
        store.ensure(kept);
        store.ensure(current);
        CHECK(source.captionCalls == QStringList(none));
        CHECK(source.segmentCalls.isEmpty());   // segments were saved and stay saved
        CHECK(!store.pending(none));
        CHECK(store.info(none).value(QStringLiteral("captions")).toList().size() == 1);
        CHECK(store.info(kept).value(QStringLiteral("captions")).toList().size() == 1);
    }
    {
        SidecarStore store(root);               // after a restart: asked once, not again
        store.setSource(&source);
        CHECK(!store.pending(none));
        store.ensure(none);
        CHECK(source.captionCalls.size() == 1);
    }
    // The second answer may be "none" as well: then it is final.
    const QString again = QStringLiteral("oldnone0002");
    writeIndex(again, 1, "[]");
    source.captions.clear();
    {
        SidecarStore store(root);
        store.setSource(&source);
        store.ensure(again);
        CHECK(source.captionCalls.size() == 2 && !store.pending(again));
    }
    {
        SidecarStore store(root);
        store.setSource(&source);
        store.ensure(again);
        CHECK(source.captionCalls.size() == 2);
    }
}

static void managerTests(const QString &dir) {
    QDir().mkpath(dir + QStringLiteral("/data/downloads"));
    library::LibraryStore library(dir + QStringLiteral("/library.db"), QStringLiteral("sidecar-library"));
    CHECK(library.open());
    // a finished download as the engine leaves it
    const QString media = dir + QStringLiteral("/data/downloads/Song [fffffffffff].m4a");
    {
        QFile f(media);
        CHECK(f.open(QIODevice::WriteOnly));
        f.write("audio");
    }
    qint64 id = 0;
    {
        DownloadQueueStore queue(library.databasePath(), QStringLiteral("sidecar-seed"));
        CHECK(queue.open());
        DownloadRecord r;
        r.videoId = "fffffffffff";
        r.kind = Kind::Audio;
        r.state = State::Done;
        r.title = "Song";
        r.directory = (dir + QStringLiteral("/data/downloads")).toStdString();
        r.fileName = "Song [fffffffffff].m4a";
        r.baseName = "Song [fffffffffff]";
        r.audioBytesTotal = r.audioBytesDone = 5;
        r.sortKey = 1;
        CHECK(queue.insert(&r));
        id = r.id;
    }

    FakeSource source;
    source.captions << track("en", false);
    source.segments << segment("sponsor", 5, 9) << segment("selfpromo", 1, 1);
    PendingResolver resolver;
    DownloadManagerConfig config;
    config.databasePath = library.databasePath();
    config.connectionName = QStringLiteral("sidecar-downloads");
    config.roots.appData = dir + QStringLiteral("/data");
    config.roots.userFolders.clear();
    config.roots.removableRoot = dir + QStringLiteral("/media");
    config.roots.refuseTemporary = false;
    config.engine.unmetered = []() { return true; };
    const QString sidecarRoot = dir + QStringLiteral("/sidecars");
    {
        DownloadManager manager(config, &resolver, nullptr);
        CHECK(manager.sidecars()->rootDirectory() == sidecarRoot); // next to the database, private
        CHECK(manager.open());
        CHECK(manager.saveCaptions() && manager.saveSegments()); // default on
        // no source yet: the local player still gets the media, extras are pending
        QVariantMap m = manager.localMedia(QStringLiteral("fffffffffff"));
        CHECK(m.value(QStringLiteral("available")).toBool());
        CHECK(m.value(QStringLiteral("videoId")).toString() == QStringLiteral("fffffffffff")); // PLY-26 history/resume
        CHECK(m.value(QStringLiteral("title")).toString() == QStringLiteral("Song"));
        CHECK(manager.localMedia(QStringLiteral("zzzzzzzzzzz")).value(QStringLiteral("videoId")).toString() == QStringLiteral("zzzzzzzzzzz"));
        CHECK(m.value(QStringLiteral("captions")).toList().isEmpty());
        CHECK(m.value(QStringLiteral("sidecarsPending")).toBool());

        QStringList changed;
        QObject::connect(&manager, &DownloadManager::itemChanged, [&changed](int, const QString &v) { changed << v; });
        manager.setSidecarSource(&source); // fetches what Done items are missing
        CHECK(source.captionCalls == QStringList() << QStringLiteral("fffffffffff"));
        CHECK(changed.contains(QStringLiteral("fffffffffff")));
        m = manager.localMedia(QStringLiteral("fffffffffff"));
        CHECK(m.value(QStringLiteral("available")).toBool());
        CHECK(!m.value(QStringLiteral("sidecarsPending")).toBool());
        const QVariantList captions = m.value(QStringLiteral("captions")).toList();
        CHECK(captions.size() == 1);
        CHECK(captions.value(0).toMap().value(QStringLiteral("path")).toString().startsWith(sidecarRoot + QLatin1Char('/')));
        CHECK(m.value(QStringLiteral("segments")).toList().size() == 1);

        // switched off: hidden from the player and remembered
        manager.setSaveCaptions(false);
        CHECK(manager.localMedia(QStringLiteral("fffffffffff")).value(QStringLiteral("captions")).toList().isEmpty());
        CHECK(manager.localMedia(QStringLiteral("fffffffffff")).value(QStringLiteral("segments")).toList().size() == 1);
    }
    {
        DownloadManager manager(config, &resolver, nullptr);
        manager.setSidecarSource(&source);
        CHECK(manager.open());
        CHECK(!manager.saveCaptions() && manager.saveSegments());
        CHECK(source.captionCalls.size() == 1); // nothing re-fetched after the restart
        manager.setSaveCaptions(true);
        CHECK(manager.localMedia(QStringLiteral("fffffffffff")).value(QStringLiteral("captions")).toList().size() == 1);
        // segments switched off: hidden from the player, remembered across a restart
        manager.setSaveSegments(false);
        CHECK(!manager.saveSegments() && !manager.sidecars()->segmentsWanted());
        CHECK(manager.localMedia(QStringLiteral("fffffffffff")).value(QStringLiteral("segments")).toList().isEmpty());
        CHECK(manager.localMedia(QStringLiteral("fffffffffff")).value(QStringLiteral("captions")).toList().size() == 1);
        {
            DownloadManagerConfig again = config;
            again.connectionName = QStringLiteral("sidecar-downloads-reopened");
            DownloadManager reopened(again, &resolver, nullptr);
            CHECK(reopened.open());
            CHECK(!reopened.saveSegments() && reopened.saveCaptions());
        }
        manager.setSaveSegments(true);
        CHECK(manager.localMedia(QStringLiteral("fffffffffff")).value(QStringLiteral("segments")).toList().size() == 1);
        // removing the download (even keeping its file) removes its extras
        CHECK(manager.remove(static_cast<int>(id), false));
        spin(50);
        CHECK(!QFileInfo(sidecarRoot + QStringLiteral("/fffffffffff")).exists());
        CHECK(QFileInfo(media).isFile());
    }
}

int main(int argc, char **argv) {
    QCoreApplication app(argc, argv);
    const QString dir = QString::fromLocal8Bit(qgetenv("TEST_DIR"));
    domainTests();
    storeTests(dir + QStringLiteral("/store/sidecars"));
    oldIndexTests(dir + QStringLiteral("/old/sidecars"));
    managerTests(dir + QStringLiteral("/manager"));
    std::printf("downloads sidecars tests: %s (%d failures)\n", failures ? "FAIL" : "PASS", failures);
    return failures ? 1 : 0;
}
